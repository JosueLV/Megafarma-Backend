CREATE TABLE usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 nombre_completo VARCHAR(150) NOT NULL,
 rol VARCHAR(30) NOT NULL,
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT ck_usuario_rol CHECK (rol IN ('ADMINISTRADOR','INVENTARIO','VENTAS'))
);
CREATE TABLE sesiones (
 id VARCHAR(36) PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 expira_en TIMESTAMP WITH TIME ZONE NOT NULL,
 revocada BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_sesiones_usuario ON sesiones(usuario_id);
CREATE INDEX ix_sesiones_expiracion ON sesiones(expira_en);
CREATE TABLE productos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo VARCHAR(50) NOT NULL UNIQUE,
 nombre VARCHAR(150) NOT NULL,
 descripcion VARCHAR(500),
 principio_activo VARCHAR(150),
 presentacion VARCHAR(100) NOT NULL,
 laboratorio VARCHAR(150),
 precio_venta NUMERIC(12,2) NOT NULL CHECK (precio_venta > 0),
 stock_minimo BIGINT NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
 creado_por VARCHAR(60) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX ix_productos_nombre ON productos(nombre);
CREATE TABLE lotes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 producto_id BIGINT NOT NULL REFERENCES productos(id),
 codigo VARCHAR(80) NOT NULL,
 fecha_vencimiento DATE NOT NULL,
 cantidad_disponible BIGINT NOT NULL CHECK (cantidad_disponible >= 0),
 creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uk_lote_producto_codigo UNIQUE(producto_id, codigo)
);
CREATE INDEX ix_lotes_vencimiento ON lotes(fecha_vencimiento);
CREATE TABLE entradas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clave_idempotencia VARCHAR(36) NOT NULL UNIQUE,
 huella VARCHAR(64) NOT NULL,
 referencia VARCHAR(120),
 observacion VARCHAR(500),
 creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
 creado_por VARCHAR(60) NOT NULL
);
CREATE TABLE movimientos_inventario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entrada_id BIGINT NOT NULL REFERENCES entradas(id),
 lote_id BIGINT NOT NULL REFERENCES lotes(id),
 tipo VARCHAR(30) NOT NULL,
 cantidad BIGINT NOT NULL CHECK (cantidad > 0),
 CONSTRAINT uk_movimiento_entrada_lote UNIQUE(entrada_id, lote_id)
);
CREATE INDEX ix_movimientos_lote ON movimientos_inventario(lote_id);
